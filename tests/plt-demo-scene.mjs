import assert from 'node:assert/strict';
import {createPLTDemoScene,PLT_DEMO_DEFAULTS,PLT_DEMO_SCENE_ID} from '../dist/plt-demo-scene.js';
import {buildPLTJob,replayPLT} from '../dist/plt-core.js';
const scene=createPLTDemoScene();
assert.equal(scene.preset,PLT_DEMO_SCENE_ID);
assert.equal(scene.triangles.length,204);
assert.equal(scene.wedges.length,89);
assert.equal(scene.unsupportedEdges.length,0);
assert.equal(scene.emitters.length,4);
assert(Math.abs(scene.emitterArea-43.76)<1e-10);
assert(scene.materials.every(m=>m.type==='diffuse'));
assert.equal(scene.demoMetadata.apertureWidth,1.2);
assert.equal(scene.demoMetadata.apertureHeight,2.9);
assert.equal(scene.demoMetadata.baffleThickness,.4);
assert.equal(PLT_DEMO_DEFAULTS.options.width,64);
assert.equal(PLT_DEMO_DEFAULTS.options.height,48);
assert.equal(PLT_DEMO_DEFAULTS.options.maxDepth,2);
assert.equal(PLT_DEMO_DEFAULTS.progressive.batchSamples,4);
assert.equal(PLT_DEMO_DEFAULTS.progressive.tileSize,32);
assert.equal(PLT_DEMO_DEFAULTS.progressive.maxRuntimeMs,600000);
assert.equal(PLT_DEMO_DEFAULTS.options.spectralMode,'monochrome');
assert.equal(PLT_DEMO_DEFAULTS.scene.emission,8);
assert.equal(PLT_DEMO_DEFAULTS.display.whitePoint,8);
assert.equal(scene.triangles.filter(t=>t.meshId===0).length,128);
// Floor materials alternate within one welded mesh. Interior tile seams must
// not become open-plate diffraction edges.
assert.equal(scene.wedges.filter(e=>e.meshId===0).length,4);
assert.throws(()=>createPLTDemoScene({emission:Infinity}),RangeError);
assert.throws(()=>createPLTDemoScene({albedo:-.1}),RangeError);
const o={...PLT_DEMO_DEFAULTS.options,width:8,height:8,samplesPerPixel:4};
const ray=await buildPLTJob(scene,scene.camera,{...o,wave:false});
const wave=await buildPLTJob(scene,scene.camera,{...o,wave:true});
const off=replayPLT(wave,wave.events.map(e=>e.directAmplitude**2));
assert(ray.reference.every(v=>Number.isFinite(v)&&v>=0));
assert(wave.reference.every(v=>Number.isFinite(v)&&v>=0));
assert(off.every(v=>Number.isFinite(v)&&v>=0));
assert(wave.stats.diffractingEvaluations>0);
assert(wave.reference.some((v,i)=>Math.abs(v-off[i])>1e-8));
assert.equal(wave.stats.twoFSDPaths,0);
assert.deepEqual(ray.camera,wave.camera);
console.log('plt demo scene: finite 3D geometry, material seams, bounded local edge response and same-camera control passed');
